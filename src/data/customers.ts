/**
 * お客様。機械ではなく、それぞれに性格と人生と想いがある。
 * セリフは必ずあたたかく。冷たい言い方は書かない。
 *
 * id と人物像は IMAGE_ASSETS.md §4 の一覧に合わせること。
 * 画像は assets/customers/<id>-normal.png / <id>-happy.png を id から自動で引く。
 */

import type { ColorTone, Impression } from './flowers';
import type { SeasonId } from './seasons';

export interface CustomerWish {
  /** 雰囲気の要望 */
  impressions: Impression[];
  /** 色の要望 */
  tones: ColorTone[];
  /** 値札を見ながら伝えてくれる、色の言い方 */
  toneLabel: string;
  /*
   * ── 「好きな花」を、やめました ──────────────────────
   *
   * ここには `loved: ['alstroemeria', 'carnation']` がありました。
   * 挨拶の紙には「アルストロメリアとカーネーションがお好きだそうです」
   * と出て、評価では 16% の重みを持っていました。
   *
   * **正解ができてしまいます。**
   * 名前を挙げられた花は、入れないといけない花になります。
   * 選ぶことが「この人に、この花を」から「言われた花を探す」に変わります。
   *
   * 残すのは、用途・雰囲気・色・予算だけ。
   * 「長もちして、あたたかい感じ」で選べれば、それで足ります。
   */
  /** 本数の好み */
  volume: 'small' | 'medium' | 'full';
}

export interface Customer {
  id: string;
  name: string;
  /** 年ごろ。断定しすぎない書き方で。 */
  age: string;
  /** 人物像（IMAGE_ASSETS.md §4 と対応） */
  persona: string;
  /** 来店したときの様子 */
  entrance: string;
  /** その人の暮らしが少しだけ見える一行 */
  life: string;
  /**
   * エプロンのメモ。
   *
   * 条件表ではなく、**人柄のメモ**。花を選んでいるあいだ、ずっと手元にある。
   * （→ design/00-emotion.md【悩む】追加①、design/13-lines.md 3章）
   *
   *   書く    贈られる人がどんな人か／好きな色・花／渡す場所・場面
   *   書かない 年齢・性別・予算の数字・分類語・**どの花が合うか**
   *
   * 3行まで。4行めが要るなら、それは条件表になりかけている。
   */
  memo: string[];
  /** 希望を伝えるセリフ */
  lines: string[];
  purpose: string;
  budget: number;
  wish: CustomerWish;
  /** 来やすい季節（ない場合はいつでも） */
  seasons?: SeasonId[];
  /** 受け取ったときの言葉。どれも笑顔で受け取ってくれる。 */
  reactions: {
    /** 想いがよく届いたとき */
    delighted: string[];
    /** 嬉しく受け取ってくれたとき */
    happy: string[];
    /** それでも必ず笑ってくれる */
    grateful: string[];
  };
  /** 帰りぎわの一言 */
  farewell: string;
}

