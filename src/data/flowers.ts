import type { SeasonId } from './seasons';

/** ブーケの印象。お客様の希望との重なりを見るのに使う。 */
export type Impression =
  | 'bright'    // 明るい・元気
  | 'lively'    // 華やか
  | 'warm'      // あたたかい
  | 'gentle'    // やさしい
  | 'elegant'   // 上品
  | 'pure'      // 清らか
  | 'natural'   // ナチュラル
  | 'calm';     // 静か

export const IMPRESSION_LABEL: Record<Impression, string> = {
  bright: '明るい',
  lively: '華やか',
  warm: 'あたたかい',
  gentle: 'やさしい',
  elegant: '上品',
  pure: '清らか',
  natural: 'ナチュラル',
  calm: '静か',
};

/** 束ねたときの役割。花屋さんの組み方にならう。 */
export type FlowerRole = 'main' | 'sub' | 'filler' | 'green';

export const ROLE_LABEL: Record<FlowerRole, string> = {
  main: '主役の花',
  sub: '寄り添う花',
  filler: 'すきまを埋める花',
  green: '葉もの',
};

export type ColorTone = 'warm' | 'cool' | 'white' | 'green';

export const TONE_LABEL: Record<ColorTone, string> = {
  warm: 'あたたかい色',
  cool: '涼しい色',
  white: '白',
  green: 'みどり',
};

export interface Flower {
  id: string;
  name: string;
  reading: string;
  /** 1本の値段（円） */
  price: number;
  /** 花言葉 */
  meanings: string[];
  /** 値札に書かれた旬 */
  seasonLabel: string;
  /** 特に生き生きしている季節 */
  seasons: SeasonId[];
  /** おすすめ用途 */
  occasions: string[];
  /** ブーケとの相性（相手の flower id） */
  goesWith: string[];
  /** 相性のひとこと */
  goesWithNote: string;
  role: FlowerRole;
  tone: ColorTone;
  impressions: Impression[];
  /** 花を眺めているときに、そっと添える言葉 */
  note: string;
  /** 花の代表色。UIの下地やぼかしに使う（花そのものは画像） */
  swatch: string;
  /** 茎の長さの目安。ブーケの高さに効く（0.8〜1.2） */
  stature: number;
}

