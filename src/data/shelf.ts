/**
 * 今日の棚。
 *
 * **棚に並ぶのは、今日市場から連れて帰った花だけです。**
 *
 * ── 前提を、途中で変えました ────────────────────────────
 *
 * ここには長いあいだ、逆のことが書いてありました。
 *
 *   「季節で花を入れ替えません。冬になったらヒマワリが棚から消えるのではなく、
 *     冬はヒマワリが奥のほうにある。好きになった花が突然いなくなると、
 *     このゲームでいちばん守りたいものが壊れます。だから消しません。」
 *
 * この決めごとは、**間違っていました。** 理由は3つです。
 *
 * **一．花屋は図書館ではありません。**
 * 本なら、全部並んでいることに意味があります。花屋は違います。
 * 季節・天候・市場・仕入れで、毎日ちがう。
 * だから「今日は会えなかった」こと自体が、花屋らしい体験になります。
 *
 * **二．消えるから、再会が生まれます。**
 * 春に毎日会っていたラナンキュラスが、夏には棚から消える。
 * 秋に久しぶりに出会う。そのとき「また会えた」になります。
 * ずっと並んでいる花に、この感情は起きません。
 *
 * **三．アルバムが、記憶になります。**
 * 棚からはいなくなる。でもアルバムにはいる。
 * 「お店には今いないけれど、私はこの花を知っている」という状態になり、
 * アルバムの存在理由そのものが強くなります。
 *
 * ── ついでに、実際の困りごとも解けました ──────────────────
 *
 * 全部を横一列に並べていたので、棚がこう伸びていました。
 *
 *   21種   画面 12.2個ぶん
 *   29種   画面 16.9個ぶん
 *   50種   画面 約29個ぶん
 *   182種  画面 約105個ぶん
 *
 * 「消さない」を守るかぎり、これは直せませんでした。
 * 前提のほうを変えたら、棚はいつでも10輪ぶんになります。
 *
 * ── 消えても、失われないこと ────────────────────────────
 *
 *   会った記録    アルバムに残る
 *   ♡好きな花     いつでも見られる
 *   花のページ    棚にいない日でも開ける
 *
 * **「好きになった花が二度と見られない」わけではありません。**
 * 店頭にいないだけで、アルバムにはいます。守りたかったものは、そこで守られています。
 */

import { marketForDay } from './market';
import type { Flower } from './flowers';
import type { SeasonId } from './seasons';

/**
 * 今日の棚の並び。
 *
 * 中身は「今日の仕入れ」そのもの（→ `marketForDay`）。
 * ここでやるのは**並べ方**だけです ── 旬のものを手前に。
 *
 * 入口に飾った花も、棚から抜きません。
 * **市場で買うのは「その花」であって「一本」ではない**からです。
 * 一本を入口の一輪挿しに挿して、残りは棚に並びます。
 *
 * 抜いてしまうと、入口の花を選ぶことに**代償**が生まれます
 * （「バラを飾ると、バラで束が組めなくなる」）。
 * 入口の花は、得も損もしないから成立しています。
 */
export function shelfFor(season: SeasonId, day: number): Flower[] {
  return [...marketForDay(day, season)].sort((a, b) => {
    const near = (f: Flower): number => (f.seasons.includes(season) ? 1 : 0);
    return near(b) - near(a);
  });
}
