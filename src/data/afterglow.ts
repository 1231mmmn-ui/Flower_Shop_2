/**
 * 余韻。お客さまが帰ったあとの、静かな店。
 *
 * ⓪感情設計書の【余韻】にこうあります。
 *
 *   > お客さまが帰ったあと、店が静かになる1.5秒。
 *   > **カウンターに、花びらが一枚残っている。**
 *
 * これは「世界が勝手に起こすこと」なのに、設計上**毎回必ず**起きていました。
 * 間隔が一定どころか100%予測できます。2日目には
 * 「ああ、また花びらか」になります（→ ⑯静けさ 3章）。
 *
 * **三日に二日くらい**に直します。
 * 残っていない日があるから、残っている日が目に入ります。
 */

/** その日の余韻に、花びらが残っているか。 */
export function petalOnCounter(day: number): boolean {
  // 三日に二日。日から決まるので、同じ日を見返しても変わらない。
  // 「昨日は残っていたか」を思い出せるのは、これが日に紐づいているからです。
  return day % 3 !== 0;
}

/**
 * 花びらの置きどころ。
 *
 * まんなかには置きません。**片づけ忘れに見せたい**ので、
 * 少し端に、少し斜めに、毎日ちがう場所へ落とします。
 * 位置も日から決めます（同じ日なら同じ場所）。
 */
export function petalPlacement(day: number): { left: number; tilt: number } {
  const a = Math.sin(day * 12.9898) * 43758.5453;
  const b = Math.sin(day * 78.233) * 12345.6789;
  const frac = (v: number) => v - Math.floor(v);
  return {
    // カウンターの左寄り／右寄り（22%〜74%）。中央は避ける。
    left: 22 + frac(a) * 52,
    tilt: -38 + frac(b) * 76,
  };
}
