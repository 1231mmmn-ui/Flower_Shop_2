/**
 * 束ね方。三つ。
 *
 * ── 一本ずつ動かす方式を、やめました ──────────────────────
 *
 * あれは「画像を配置する操作」でした。
 * うまく置けたか／置けなかったか、という話になっていて、
 * うまく置けても嬉しくなく、置けないと自分が下手に思えました。
 *
 * ここでしてほしいのは、そういうことではありません。
 *
 *   「この人には、どんな束が似合うだろう」
 *
 * と考える時間です。だから、**こちらが最後まで組んだ束を三つ出します。**
 * 三つとも成立しています。**優劣も、正解も、点数もありません。**
 * どれを選んでも、お客さまの受け取り方は変わりません（→ evaluation.ts）。
 *
 * ── 2026-08-13、「結束点から組む」考え方に作り直しました ─────────
 *
 * 前までは、花ごとに角度・伸びの幅（spread・mainSpreadFactor…）を
 * 別々のノブで揺らしていました。結束点（すべての茎が集まる一点）
 * から見て「毎回どれくらい散らばるか」を決めているだけで、
 * 「花束としてどんな形に見えるか」を直接は決めていなかった。
 * 数値をいくら足しても、最後は「一輪素材をその範囲内にばら撒いた」
 * ものにしかならなかった。
 *
 * ここでは逆に、**先に外形を決めます。** 主役の花が「面」を作る
 * 位置（`coreAttractors`）と、葉物が外へ抜ける位置
 * （`edgeAttractors`）を、結束点からの角度・伸びで名指しします。
 * 丸くやわらかい・高さを出してすっきり・自然に広がるは、この
 * 位置の並びそのものが違う ── 「同じ骨格を数値で変形させたもの」
 * ではなく、**違う骨格**です（→ src/game/bunch.ts）。
 */

import type { BouquetStyleId } from './types';

/** 結束点から見た、ひとつの目安位置。 */
export interface Attractor {
  /** 結束点から見た角度（度）。0 が真上、負が左、正が右。 */
  angle: number;
  /** 結束点からの伸び（0〜1）。0 が結束点そのもの。 */
  reach: number;
}

export interface BouquetStyle {
  id: BouquetStyleId;
  /** 選ぶときに読む名前。効果ではなく、形の話だけを書く。 */
  name: string;
  /** 一行だけ。良し悪しは言わない。 */
  note: string;
  /**
   * 主役の花が「面」を作る、核になる位置。
   *
   * 選んだ主役の花は、ここへ順に収まります（多ければ分け合い、
   * 少なければ同じ花が隣の位置にも広がります）。この並びの形が、
   * そのままブーケの輪郭の骨組みになります。
   */
  coreAttractors: Attractor[];
  /**
   * 葉物・ラインの花が外へ抜ける先。
   *
   * 主役の並び（coreAttractors）よりも外側・遠くを指すことで、
   * 輪郭のふちを作ります。
   */
  edgeAttractors: Attractor[];
  /**
   * 一本ずつのばらつき（0〜1）。0 なら整然、1 ならかなり自然。
   * 角度・伸び・傾きの揺れ幅を直接広げます（→ src/game/bunch.ts）。
   */
  scatter: number;
  /**
   * 包み紙の広がり。束の輪郭に合わせて紙も変わる。
   * 幅と高さの倍率で、1.0 が基準。
   */
  paper: { width: number; height: number };
}

