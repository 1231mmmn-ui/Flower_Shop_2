/**
 * 束ね方。三つ。
 *
 * ── 一本ずつ動かす方式を、やめました ──────────────────────
 *
 * あれは「画像を配置する操作」でした。
 * うまく置けたか／置けなかったか、という話になっていて、
 * うまく置けても嬉しくなく、置けないと自分が下手に思えました。
 *
 * ここでしてほしいのは、そういうことではありません。
 *
 *   「この人には、どんな束が似合うだろう」
 *
 * と考える時間です。だから、**こちらが最後まで組んだ束を三つ出します。**
 * 三つとも成立しています。**優劣も、正解も、点数もありません。**
 * どれを選んでも、お客さまの受け取り方は変わりません（→ evaluation.ts）。
 *
 * ── 三つの違いは、何で作るか ────────────────────────────
 *
 *   丸くやわらかい   角度を広く、伸びをそろえる    → まるい輪郭
 *   高さを出してすっきり 角度を狭く、真ん中を高く   → 縦に立つ輪郭
 *   自然に広がる     角度も伸びも、一本ずつずらす  → 揺れのある輪郭
 *
 * どれも花屋が実際に組む形です。
 * 「派手な形」「珍しい形」は入れません ── 選ぶ理由が
 * 「その人に似合うか」から「見栄えがするか」へ移るので。
 */

import type { BouquetStyleId } from './types';

export interface BouquetStyle {
  id: BouquetStyleId;
  /** 選ぶときに読む名前。効果ではなく、形の話だけを書く。 */
  name: string;
  /** 一行だけ。良し悪しは言わない。 */
  note: string;
  /**
   * 扇の広がり（度）。端の花が何度まで倒れるか。
   *
   * ── 広げました（38 → 54）──────────────────────────
   *
   * 束のかたまりを測ったら、**169px 幅 × 235px 高さ**でした。
   * 縦に細長い。花屋の束を正面から見ると、逆です（横に広い）。
   * 縦に伸びていたぶん、顔を隠さないためには小さくするしかなく、
   * 「もっと大きく」と両立しませんでした。
   *
   * 角度を広げ、中心の抜け（crown）を下げると、
   * 同じ本数のまま**低く広い**かたまりになります。
   */
  spread: number;
  /**
   * 主役が、扇の広がりのうち何割まで使うか（0〜1）。
   *
   * 主役まで縁いっぱいに散らすと、花の顔どうしが離れて重ならず、
   * 「扇状に並べたコラージュ」に見えました。主役だけ扇の中心寄りに
   * 抑え、寄り添う花・小花・葉ものは通常どおり縁まで使うと、
   * 主役の顔が重なり合う「かたまり」が中心にでき、そのまわりに
   * 縁取りが広がる、という花屋らしい構造になります。
   */
  mainSpreadFactor: number;
  /**
   * 中心の花が、どれだけ抜けて高いか。
   * 0 なら全部おなじ高さ、1 なら真ん中だけ大きく伸びる。
   */
  crown: number;
  /**
   * 外側の花が、どれだけ低く落ちるか。
   *
   * **0.2 は落としすぎでした。** 外側の花が紙の口と同じ高さに来て、
   * 紙の横から生えているように見えました。花屋の束は、
   * 外側の花も必ず紙の口より上にあります。
   */
  drop: number;
  /**
   * 一本ずつのばらつき。0 なら整然、1 ならかなり自然。
   *
   * 角度・伸び・傾きの揺れ幅を直接広げます（→ src/game/bunch.ts の jitter）。
   */
  scatter: number;
  /**
   * 外周へ抜ける役（ユーカリなどの葉もの、寄り添う花のごく弱い版）
   * を、どこまで外へ出すか（0〜1）。
   *
   * 「丸くやわらかい」で枝を遠くまで飛ばすと、ドームの輪郭そのものが
   * 崩れて見えました。輪郭を優先する形ほど低く、抜け感を主役にする
   * 「自然に広がる」ほど高くします。
   */
  peripheralEscape: number;
  /**
   * 主役自身の顔にも、左右・前後の個体差をどれだけ持たせるか（0〜1）。
   *
   * ── 「全部、縦長」に見えていた理由 ────────────────────
   *
   * ユーカリなど外周へ抜ける役だけを動かし、主役（バラ・アジサイ）は
   * 帯（band）の中心にきれいに積んでいました。結果、「中心の花束＋
   * 外へ流した枝」という同じ骨格が3スタイルとも残り、"自然に広がる"
   * でも花の顔そのものは動いていませんでした。ここを効かせると、
   * 主役の side・ring にも個体ごとの揺れが乗り、"バラが右上、
   * アジサイが左下" のような輪郭の不整形が主役自身に生まれます。
   * ドームの一体感を守りたい「丸くやわらかい」は低く、
   * 「自然に広がる」は高くします。
   */
  mainDrift: number;
  /**
   * 包み紙の広がり。束の輪郭に合わせて紙も変わる。
   * 幅と高さの倍率で、1.0 が基準。
   */
  paper: { width: number; height: number };
}

